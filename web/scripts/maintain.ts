/**
 * Nightly maintenance loop (SPEC §6.9) — deterministic, no LLM.
 *
 * For each local workspace (or --ws <id>):
 *   1. sync      — detect drift since last snapshot, refresh _Index/_Model
 *   2. audit     — full lint, stored as an audit row (health history)
 *   3. bundles   — rebuild every bundle IF drift was detected
 *   4. digest    — write _Digest.md at the workspace root: what changed,
 *                  what awaits review, what went stale, bundle freshness
 *
 * Quiet nights stay quiet: no drift → no bundle churn, no journal writes;
 * only the digest timestamp moves (excluded from sync/review/ST-004).
 *
 * Run: npm run maintain [-- --ws 3]
 */
import { q } from "../src/lib/db";
import { connectorFor } from "../src/lib/hub";
import { applySyncSvc, runAuditSvc, listBundlesSvc, refreshBundleSvc } from "../src/lib/service";
import { getReviewQueue } from "../src/lib/review";
import { computeInsights } from "../src/lib/graph-insights";
import { diffCount } from "../src/lib/sync";

const argWs = (() => {
  const i = process.argv.indexOf("--ws");
  return i > -1 ? Number(process.argv[i + 1]) : null;
})();

function line(s = "") {
  process.stdout.write(s + "\n");
}

async function maintain(wsId: number): Promise<void> {
  const ws = q.getWorkspace(wsId);
  if (!ws) throw new Error(`Workspace ${wsId} not found`);
  if (ws.kind !== "local") {
    line(`- skipping ${ws.name} (${ws.kind} — local maintenance only)`);
    return;
  }
  const c = connectorFor(ws);
  const now = new Date().toISOString().slice(0, 16).replace("T", " ");
  line(`\n== ${ws.name} (#${ws.id}) — ${now} ==`);

  // 1. sync (refreshes projections; journals only when drift exists)
  const sync = await applySyncSvc(wsId);
  const drift = diffCount(sync.report.diff);
  line(`sync: ${drift} change(s) since last sync`);

  // 2. audit
  const { result } = await runAuditSvc(wsId);
  const { errors, warns } = result.stats as { errors: number; warns: number };
  const stale = result.findings.filter((f) => f.rule === "TR-001");
  line(`audit: ${errors} error(s), ${warns} warning(s), ${stale.length} stale`);

  // 3. bundles — rebuild only when something actually changed
  const bundles = await listBundlesSvc(wsId);
  if (drift > 0) {
    for (const b of bundles) {
      try {
        await refreshBundleSvc(wsId, b.id);
        line(`bundle rebuilt: ${b.name}`);
      } catch (e) {
        line(`bundle FAILED: ${b.name} — ${e instanceof Error ? e.message : e}`);
      }
    }
  } else {
    line(`bundles: unchanged (no drift)`);
  }

  // 4. review queue + graph insights + digest
  const queue = await getReviewQueue(c, wsId);
  const gi = await computeInsights(c).catch(() => ({ insights: [], stats: {} as Record<string, number> }));
  const fresh = await listBundlesSvc(wsId);

  const digest = [
    `# Workspace digest`,
    ``,
    `> Generated by the nightly maintenance loop — deterministic, no AI.`,
    `> Last run: ${now}. This file is a status board, not knowledge: it is`,
    `> excluded from sync, review, and bundles.`,
    ``,
    `## Needs you`,
    queue.items.length
      ? `- **${queue.items.length} change(s) await your review** → open the app's Review page.`
      : `- Review queue is clear.`,
    ...(queue.flags.length
      ? [`- **${queue.flags.length} flagged file(s)** await an agent fix-up (scaffold on the Review page).`]
      : []),
    ...(errors ? [`- **${errors} protocol error(s)** — run a repair proposal.`] : []),
    ...(stale.length
      ? [
          `- **${stale.length} file(s) past stale_after** — re-verify or deprecate:`,
          ...stale.map((f) => `  - \`${f.path}\` — ${f.message}`),
        ]
      : []),
    ``,
    `## Graph insights`,
    ...(gi.insights.length
      ? gi.insights.slice(0, 8).map((i) => `- **${i.kind}** — ${i.title}`)
      : ["- No structural findings."]),
    ``,
    `## Health`,
    `- Audit: ${errors} errors · ${warns} warnings`,
    `- Drift synced this run: ${drift} file(s)` +
      (drift
        ? ` (${sync.report.diff.modified.length} modified, ${sync.report.diff.added.length} added, ${sync.report.diff.removed.length} removed)`
        : ""),
    ``,
    `## Bundles`,
    ...(fresh.length
      ? fresh.map(
          (b) =>
            `- **${b.name}** — ${b.stats?.concepts ?? "?"} concepts` +
            (b.stats?.references ? ` (${b.stats.references} reference docs)` : "") +
            ` · built ${b.updatedAt}`,
        )
      : ["- (none)"]),
    ``,
  ].join("\n");

  await c.write("_Digest.md", digest, { overwrite: true });
  line(`digest written: _Digest.md (review: ${queue.items.length} pending, ${queue.flags.length} flagged)`);
}

async function main() {
  const targets = argWs ? [argWs] : q.listWorkspaces().filter((w) => w.kind === "local").map((w) => w.id);
  for (const id of targets) {
    try {
      await maintain(id);
    } catch (e) {
      line(`ERROR maintaining workspace ${id}: ${e instanceof Error ? e.message : e}`);
      process.exitCode = 1;
    }
  }
}

void main();
